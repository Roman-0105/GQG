-- Этап 14 (23.09.2026, по запросу владельца платформы):
--  - архивирование работников (не удалять из истории распределений, но
--    скрыть из активных списков назначения)
--  - удаление работников (для DELETE отдельная RLS-политика не нужна —
--    workers_write_management уже "for all", т.е. включает DELETE)
--  - удаление пользователей (profiles) — раньше такой политики не было
--    вообще, ни у кого, включая management (см. CLAUDE.md — тот же
--    пробел, что был у reports до миграции 0011)
-- ============================================================================

-- Архивирование — мягкое скрытие, не удаление: у работника может быть
-- история (task_worker_assignments, org_positions.assigned_worker_id),
-- терять её незачем. NULL = активен, дата = когда заархивирован.
alter table workers add column archived_at timestamptz;

-- Удалить пользователя может только management, НЕ самого себя (иначе
-- легко случайно остаться без единственного гендира/техдира без возможности
-- восстановиться иначе как через SQL) и НЕ профиль с role='developer',
-- если сам не разработчик — тот же принцип невидимости/неприкосновенности,
-- что и у insert/update (см. миграцию 0012).
--
-- Важно: это удаляет ТОЛЬКО строку profiles. Саму учётную запись в
-- Supabase Auth (auth.users) удалить с фронтенда нельзя в принципе — для
-- этого нужен service_role/admin API, которого в проекте сознательно нет
-- (см. CLAUDE.md). После удаления профиля человек формально всё ещё может
-- авторизоваться в Auth, но RLS не даст сделать в приложении вообще ничего
-- без профиля — на практике равносильно полному отзыву доступа.
--
-- Если у пользователя есть история (author_id/foreman_id/created_by/
-- approved_by в заданиях и сводках, assigned_foreman_id в workers) —
-- обычный foreign key БЕЗ каскада заблокирует удаление с понятной
-- ошибкой (foreign_key_violation), а не молча снесёт историю. Это
-- осознанное поведение, не баг — приложение показывает дружелюбное
-- сообщение об этом (см. UsersList.tsx).
create policy "profiles_delete_management"
  on profiles for delete
  using (
    is_management()
    and id <> auth.uid()
    and (role <> 'developer' or is_developer())
  );
