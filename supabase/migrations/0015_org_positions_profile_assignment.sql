-- ============================================================================
-- Этап 15 (24.09.2026, по факту использования владельцем платформы):
-- назначение на должность в оргструктуре ТОЛЬКО из справочника workers
-- оказалось неудобным для позиций, которые и так уже являются реальными
-- логин-пользователями (Генеральный директор, Технический директор,
-- Начальник буровой партии) — заводить их ЕЩЁ РАЗ как "работника" только
-- ради оргструктуры избыточно и путает (человек уже есть в БД, а выбрать
-- его было нельзя).
--
-- Решение: должность теперь может ссылаться ЛИБО на workers, ЛИБО на
-- profiles (не оба сразу) — на выбор в каждом конкретном случае. Для
-- позиций без логина (геолог, техник, машинист и т.п.) по-прежнему
-- используется workers, как и раньше.
-- ============================================================================

alter table org_positions add column assigned_profile_id uuid references profiles(id) on delete set null;

alter table org_positions add constraint org_positions_one_assignee check (
  num_nonnulls(assigned_worker_id, assigned_profile_id) <= 1
);
