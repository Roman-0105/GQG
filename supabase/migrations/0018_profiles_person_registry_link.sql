-- ============================================================================
-- Этап 18 (25.09.2026, по запросу владельца платформы): "Выдать доступ"
-- существующему работнику вместо повторного ввода ФИО с нуля при заведении
-- логина — построено поверх person-centric оргструктуры из миграции 0016.
--
-- Зафиксированные решения:
--  1. НЕ объединяем profiles/workers в одну таблицу и НЕ переименовываем
--     workers на уровне SQL — слишком большой blast radius для одного
--     прохода (решение (2) из 0016 подтверждено повторно: экраны
--     "Пользователи"/"Работники" остаются раздельными вкладками). Меняется
--     только рабочий процесс создания пользователя, сама таблица остаётся
--     workers.
--  2. Связь "это тот же человек, что и в реестре" — новое поле
--     profiles.person_id → workers(id), nullable, БЕЗ обратного переноса
--     истории: старые task_worker_assignments.worker_id и чужие
--     reports_to_worker_id, указывающие на старую строку workers, НЕ
--     перевязываются на новый профиль (ниже риск, чем переписывать
--     историю задним числом). person_id нужен только для отображения
--     "это тот же человек" и чтобы не дать выдать доступ одному и тому же
--     работнику дважды (unique constraint ниже).
--  3. При "выдаче доступа" (UsersList.tsx / WorkersSettings.tsx) старая
--     строка workers архивируется (archived_at) и теряет position_id —
--     теми же существующими механизмами, что и обычное архивирование
--     работника / "Убрать из схемы" в OrgChart.tsx (миграции 0014, 0016).
--     Новых колонок под это не заводим, фронтенд просто вызывает оба
--     UPDATE одним запросом сразу после создания профиля.
--  4. workers.organization_id НЕ трогаем — не требуется для этой задачи,
--     не расширяем миграцию сверх того, что было запрошено.
-- ============================================================================

alter table profiles add column person_id uuid references workers(id) on delete set null;

-- Один и тот же работник не может быть "выдан доступ" дважды — иначе два
-- профиля считали бы себя одним и тем же человеком.
alter table profiles add constraint profiles_person_id_unique unique (person_id);

comment on column profiles.person_id is
  'Ссылка на исходную строку workers, если этот логин выдан существующему работнику из реестра персонала ("Выдать доступ" в WorkersSettings.tsx / UsersList.tsx) — НЕ переносит историю (task_worker_assignments/reports_to_* у старой строки workers остаются как есть), только связывает "это тот же человек" для отображения. NULL — для профилей, созданных с нуля, и для всех профилей, существовавших до этой миграции (обратной синхронизации/бэкфилла не делается).';
