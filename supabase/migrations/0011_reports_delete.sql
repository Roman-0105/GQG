-- ============================================================================
-- Этап 11: удаление сводок (20.09.2026, по запросу заказчика). На таблице
-- reports вообще не было DELETE-политики — ни автор, ни management не
-- могли удалить сводку через приложение, только вручную через Supabase
-- Table Editor (см. CLAUDE.md, было явно зафиксировано как ограничение).
--
-- Теперь:
--  - автор может удалить СВОЙ черновик (approval_status = 'draft') —
--    отправленную/согласованную/отклонённую сводку удалить через это
--    нельзя, это уже часть истории (отклонённую — только исправить через
--    edit_unlocked, см. решение 19.09.2026)
--  - management может удалить любую сводку в любом статусе (в т.ч. для
--    уборки тестовых/ошибочных данных)
--
-- report_costs уже связаны с reports через "on delete cascade"
-- (миграция 0001) — отдельная политика на удаление затрат не нужна,
-- строки уйдут вместе со сводкой автоматически.
-- ============================================================================

create policy "reports_delete_own_draft"
  on reports for delete
  using (author_id = auth.uid() and approval_status = 'draft');

create policy "reports_delete_management"
  on reports for delete
  using (is_management());
